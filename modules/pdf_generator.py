import io
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors

def generate_proposal_pdf(proposal):
    """Generates an official committee endorsement PDF summary sheet."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()
    
    # Custom Styles
    header_style = ParagraphStyle(
        'HeaderStyle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=18,
        textColor=colors.HexColor('#0F172A'),
        spaceAfter=6
    )
    
    sub_header_style = ParagraphStyle(
        'SubHeaderStyle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=10,
        textColor=colors.HexColor('#475569'),
        spaceAfter=15
    )
    
    section_style = ParagraphStyle(
        'SectionStyle',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=12,
        textColor=colors.HexColor('#1E293B'),
        spaceBefore=12,
        spaceAfter=6
    )
    
    body_style = ParagraphStyle(
        'BodyStyle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        textColor=colors.HexColor('#334155'),
        leading=14,
        spaceAfter=6
    )

    story = []

    # Document Header
    story.append(Paragraph("SGWVM TECHNOLOGY LIMITED", header_style))
    story.append(Paragraph("Legislative Strategic Outreach & Proposal Evaluation Sheet", sub_header_style))
    story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#2563EB'), spaceAfter=15))

    # Proposal Details
    company = proposal.get('company_name', 'N/A')
    title = proposal.get('project_title', 'N/A')
    email = proposal.get('email', 'N/A')
    status = proposal.get('status', 'Pending').upper()
    submitted = proposal.get('created_at', 'N/A')
    summary = proposal.get('ai_summary', 'No summary available.').replace('\n', '<br/>')
    notes = proposal.get('admin_notes', 'None recorded.')

    story.append(Paragraph(f"<b>Proposal Reference ID:</b> #{proposal.get('id', 'N/A')}", body_style))
    story.append(Paragraph(f"<b>Company / Vendor:</b> {company}", body_style))
    story.append(Paragraph(f"<b>Project Title:</b> {title}", body_style))
    story.append(Paragraph(f"<b>Vendor Contact Email:</b> {email}", body_style))
    story.append(Paragraph(f"<b>Submission Date:</b> {submitted}", body_style))
    story.append(Paragraph(f"<b>Current Evaluation Status:</b> <font color='#2563EB'><b>{status}</b></font>", body_style))

    story.append(Spacer(1, 10))
    story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor('#CBD5E1'), spaceAfter=10))

    # AI Summary Section
    story.append(Paragraph("🤖 AI Executive Summary & Technical Scope", section_style))
    story.append(Paragraph(summary, body_style))

    story.append(Spacer(1, 10))
    story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor('#CBD5E1'), spaceAfter=10))

    # Committee Notes
    story.append(Paragraph("📝 Committee Evaluation & Admin Notes", section_style))
    story.append(Paragraph(notes, body_style))

    story.append(Spacer(1, 20))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor('#94A3B8'), spaceAfter=15))
    story.append(Paragraph("<i>Official document generated by SGWVM Legislative Management System.</i>", ParagraphStyle('Foot', parent=styles['Italic'], fontSize=8, textColor=colors.HexColor('#64748B'))))

    doc.build(story)
    buffer.seek(0)
    return buffer.getvalue()
